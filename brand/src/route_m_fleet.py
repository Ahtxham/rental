"""
Musafir Fleet: the same Route M, with "Fleet" beside it, so it reads "M Fleet".

The fleet portal and driver app (the `mydriver` repo) are the second product
under the Musafir name. They take the mark exactly as `route_m.py` draws it;
only the word changes. "Fleet" takes the accent the way "Cars" does on the
rental lockup: the M is the brand, the word after it is the product.

Writes the files into `logo/musafir-fleet/`, named for where each one goes:

    web/      Next.js file icons, the PWA icons, and `logo-art.ts`, the
              geometry the portal draws its logo from as inline SVG
    mobile/   every icon Expo asks for (iOS light/dark/tinted, Android
              adaptive layers, Play Store) and the sign-in lockups

Copy them into the app repo with `copy-to-mydriver.sh` beside them.

    python src/route_m.py && python src/route_m_fleet.py
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
import route_m  # noqa: E402
from route_m import (  # noqa: E402
    BASELINE,
    BBOX,
    GAP,
    MIDNIGHT,
    ORIGIN,
    PIN,
    ROUTE,
    SAFFRON,
    SAFFRON_INK,
    SCHEMES,
    STROKE,
    TRACKING,
    WHITE,
    WORD_AXES,
    WORD_SIZE,
    _pin_path,
    _svg,
    contrast,
    mark,
    svg_to_png,
)
from typeset import typeset  # noqa: E402

OUT = route_m.OUT.parent / "musafir-fleet"
WEB, MOBILE = OUT / "web", OUT / "mobile"

# iOS 18 tinted icons are rendered from luminance, so the accent is a grey a
# step down from the road rather than a colour that would be thrown away.
SCHEMES["tinted"] = {"road": WHITE, "accent": "#a6a6a6", "word": WHITE, "cars": "#a6a6a6"}

FLEET = typeset("Fleet", size=WORD_SIZE, tracking=TRACKING, **WORD_AXES)
X0, Y0, X1, Y1 = BBOX
WORD_X = X1 + GAP
LOCKUP_W = WORD_X + FLEET.width - X0
LOCKUP_H = Y1 - Y0


def lockup(scheme: str) -> str:
    s = SCHEMES[scheme]
    body = mark(scheme) + (
        f'<g transform="translate({WORD_X:.2f},{BASELINE:g})" fill="{s["cars"]}">{FLEET.d}</g>'
    )
    return _svg((X0, Y0, LOCKUP_W, LOCKUP_H), body)


def tile(px: int, fill: float, *, ground: str | None, scheme: str = "dark") -> str:
    """The mark centred on a square, its ink `fill` of the width. No ground = transparent."""
    k = (fill * px) / (X1 - X0)
    tx = px / 2 - k * (X0 + X1) / 2
    ty = px / 2 - k * (Y0 + Y1) / 2
    bg = f'<rect width="{px}" height="{px}" fill="{ground}"/>' if ground else ""
    body = bg + f'<g transform="translate({tx:.3f},{ty:.3f}) scale({k:.5f})">{mark(scheme)}</g>'
    return _svg((0, 0, px, px), body, (px, px))


def solid(px: int, colour: str) -> str:
    return _svg((0, 0, px, px), f'<rect width="{px}" height="{px}" fill="{colour}"/>', (px, px))


# Android's adaptive icon is a 108dp canvas of which a 66dp circle is safe from
# every launcher's mask. The mark's diagonal has to sit inside that circle, which
# caps its width at about 45% of the canvas; 42% leaves a margin.
ANDROID_FILL = 0.42

FILES: dict[str, tuple[str, int]] = {
    # Next.js file conventions. `icon` doubles as the favicon, so the mark fills
    # more of it: at 16px there is no room for padding.
    "web/icon.png": (tile(1024, 0.80, ground=MIDNIGHT), 1024),
    "web/apple-icon.png": (tile(1024, 0.64, ground=MIDNIGHT), 1024),
    "web/icon-192.png": (tile(192, 0.64, ground=MIDNIGHT), 192),
    "web/icon-512.png": (tile(512, 0.64, ground=MIDNIGHT), 512),
    # Expo. iOS masks the square itself, so the light icon is full-bleed and
    # opaque; dark and tinted are transparent and iOS supplies the ground.
    "mobile/icon.png": (tile(1024, 0.62, ground=MIDNIGHT), 1024),
    "mobile/ios-icon-light.png": (tile(1024, 0.62, ground=MIDNIGHT), 1024),
    "mobile/ios-icon-dark.png": (tile(1024, 0.62, ground=None), 1024),
    "mobile/ios-icon-tinted.png": (tile(1024, 0.62, ground=None, scheme="tinted"), 1024),
    "mobile/android-icon-foreground.png": (tile(1024, ANDROID_FILL, ground=None), 1024),
    "mobile/android-icon-background.png": (solid(1024, MIDNIGHT), 1024),
    "mobile/android-icon-monochrome.png": (tile(1024, ANDROID_FILL, ground=None, scheme="white"), 1024),
    "mobile/play-store-icon.png": (tile(512, 0.62, ground=MIDNIGHT), 512),
    "mobile/splash-icon.png": (tile(1024, 0.50, ground=None), 1024),
    "mobile/favicon.png": (tile(96, 0.80, ground=MIDNIGHT), 96),
}


def logo_art() -> str:
    """
    The geometry as a TypeScript module, so the portal draws the logo inline
    and colours it from theme tokens instead of shipping one image per theme.
    """
    glyphs = [
        {"t": m.group(1), "d": m.group(2)}
        for m in re.finditer(r'<path transform="([^"]+)" d="([^"]+)"/>', FLEET.d)
    ]
    ox, oy, orr = ORIGIN
    return (
        "// Generated by rental/brand/src/route_m_fleet.py. Do not edit by hand:\n"
        "// change the generator and copy the output across.\n\n"
        f'export const MARK_VIEWBOX = "{X0:g} {Y0:g} {X1 - X0:g} {Y1 - Y0:g}";\n'
        f'export const LOGO_VIEWBOX = "{X0:g} {Y0:g} {LOCKUP_W:.2f} {LOCKUP_H:g}";\n'
        f'export const ROAD = "{ROUTE}";\n'
        f"export const ROAD_WIDTH = {STROKE};\n"
        f"export const ORIGIN = {{ cx: {ox:g}, cy: {oy:g}, r: {orr:g} }};\n"
        f'export const PIN = "{_pin_path(*PIN)}";\n'
        f'export const WORD_TRANSFORM = "translate({WORD_X:.2f},{BASELINE:g})";\n'
        f"export const WORD: ReadonlyArray<{{ t: string; d: string }}> = {json.dumps(glyphs)};\n"
    )


COPY_SCRIPT = """#!/bin/sh
# Copy the generated Musafir Fleet files into the app repo. Run from anywhere.
set -e
HERE="$(cd "$(dirname "$0")" && pwd)"
APP="${1:-$HOME/Documents/invo/mydriver}"
cp "$HERE/web/icon.png" "$HERE/web/apple-icon.png" "$APP/web/src/app/"
cp "$HERE/web/icon-192.png" "$HERE/web/icon-512.png" "$APP/web/public/"
mkdir -p "$APP/web/src/components/brand"
cp "$HERE/web/logo-art.ts" "$APP/web/src/components/brand/logo-art.ts"
for f in "$HERE"/mobile/*.png; do cp "$f" "$APP/mobile/assets/"; done
echo "Copied. Now regenerate the iOS launch screens: cd $APP/web && npm run splash"
"""


def main() -> None:
    for d in (WEB, MOBILE):
        d.mkdir(parents=True, exist_ok=True)
    for scheme in ("dark", "light", "one-colour", "white"):
        (OUT / f"lockup-{scheme}.svg").write_text(lockup(scheme))
    # The sign-in screen lockups, 3x a 220pt width so they stay sharp on any phone.
    for scheme in ("dark", "light"):
        w = 660
        svg_to_png(lockup(scheme), MOBILE / f"logo-lockup-{scheme}.png", w, round(w * LOCKUP_H / LOCKUP_W))
    for rel, (svg, px) in FILES.items():
        svg_to_png(svg, OUT / rel, px, px)
        # Chrome always writes RGBA. An icon with a ground must go out with no
        # alpha channel at all: App Store Connect rejects one that has it, even
        # fully opaque, and says so only after the upload.
        if "<rect" in svg:
            from PIL import Image

            with Image.open(OUT / rel) as img:
                img.convert("RGB").save(OUT / rel)
    (WEB / "logo-art.ts").write_text(logo_art())
    copy = OUT / "copy-to-mydriver.sh"
    copy.write_text(COPY_SCRIPT)
    copy.chmod(0o755)

    for label, a, b in [
        ("Midnight word on white", MIDNIGHT, WHITE),
        ("Saffron ink on white", SAFFRON_INK, WHITE),
        ("Saffron ink on #f1f5f9 page", SAFFRON_INK, "#f1f5f9"),
        ("Saffron on midnight", SAFFRON, MIDNIGHT),
        ("White on midnight", WHITE, MIDNIGHT),
    ]:
        print(f"{contrast(a, b):5.2f}:1  {label}")
    print(f"wrote {len(FILES) + 2} png, 4 lockups and logo-art.ts to {OUT}")


if __name__ == "__main__":
    main()
